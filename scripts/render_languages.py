#!/usr/bin/env python3
"""Render language-breakdown cards with the abyssal-navy art style.

Reads bot-stats.json (generated by github_stats.py) and paints one card per
language with repo counts and a color swatch.
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from theme import W, defs, canvas, close_svg, card, FONT, MONO

STATS_JSON = Path(__file__).parent.parent / "bot-stats.json"


def render(stats):
    langs = stats.get("languages", [])
    parts = []
    parts.append(canvas(W, 420, "l", "Languages & Stack",
                        "Repositories by primary language • live from the GitHub API",
                        f"Updated {stats.get('generated_at','')[:10]}"))
    parts.append(defs("l"))

    # Header stat bar
    parts.append(card(28, 100, 904, 70))
    parts.append(
        f'  <text x="46" y="122" fill="#e9eefb" font-size="15" font-weight="700" '
        f'font-family="{FONT}">{stats["total_repos"]} repositories</text>'
    )
    parts.append(
        f'  <text x="46" y="140" fill="#8d9cc4" font-size="11" font-family="{MONO}">'
        f'{stats["public_repos"]} public • {stats["private_repos"]} private • '
        f'{stats["original_repos"]} original • {stats["forked_repos"]} forks</text>'
    )
    parts.append(
        f'  <text x="{W - 74}" y="122" fill="#22d3ee" font-size="14" font-weight="700" '
        f'text-anchor="end" font-family="{FONT}">{stats["stars"]} stars</text>'
    )
    parts.append(
        f'  <text x="{W - 74}" y="140" fill="#8d9cc4" font-size="11" font-family="{MONO}">'
        f'{stats["watchers"]} watchers • {stats["open_issues"]} open issues</text>'
    )

    # Language cards
    y = 195
    gap = 12
    card_w = (904 - gap * (len(langs) - 1)) / len(langs) if langs else 0
    card_w = max(card_w, 110)
    x = 28
    for lang in langs:
        name = lang["name"]
        count = lang["count"]
        color = lang["color"]
        pct = count / stats["total_repos"] * 100 if stats["total_repos"] else 0
        parts.append(card(x, y, card_w, 170, accent=color, prefix="l"))
        parts.append(
            f'  <circle cx="{x + 14}" cy="{y + 22}" r="8" fill="{color}"/>'
        )
        parts.append(
            f'  <text x="{x + 30}" y="{y + 25}" fill="#e9eefb" font-size="13" font-weight="700" '
            f'font-family="{FONT}">{name}</text>'
        )
        parts.append(
            f'  <text x="{x + card_w / 2}" y="{y + 72}" fill="#8d9cc4" font-size="10" '
            f'text-anchor="middle" font-family="{MONO}">{count} repo{"s" if count != 1 else ""}</text>'
        )
        parts.append(
            f'  <rect x="{x + 16}" y="{y + 96}" width="{card_w - 32}" height="10" rx="5" '
            f'fill="#142040" stroke="#223154" stroke-width="1"/>'
        )
        parts.append(
            f'  <rect x="{x + 16}" y="{y + 96}" width="{max((card_w - 32) * pct / 100, 2):.1f}" height="10" rx="5" '
            f'fill="{color}"/>'
        )
        parts.append(
            f'  <text x="{x + card_w / 2}" y="{y + 118}" fill="#e9eefb" font-size="11" font-weight="700" '
            f'text-anchor="middle" font-family="{FONT}">{pct:.1f}%</text>'
        )
        parts.append(
            f'  <text x="{x + card_w / 2}" y="{y + 150}" fill="#5b6a90" font-size="9" '
            f'text-anchor="middle" font-family="{MONO}">of all repositories</text>'
        )
        x += card_w + gap

    parts.append(close_svg([]))
    return "\n".join(parts)


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(".")
    out.mkdir(parents=True, exist_ok=True)
    if not STATS_JSON.exists():
        print("ERROR: bot-stats.json not found — run github_stats.py first", file=sys.stderr)
        return 1
    stats = json.loads(STATS_JSON.read_text())
    svg = render(stats)
    svg_path = out / "languages.svg"
    svg_path.write_text(svg)
    print(f"Languages chart → {svg_path} ({len(svg)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
