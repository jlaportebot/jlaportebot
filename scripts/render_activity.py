#!/usr/bin/env python3
"""Render the GitHub activity chart with the new abyssal-navy art style.

Reads gh-activity-chart.json (regenerated by gh_activity_chart.py) and paints
five cumulative series as neon lines over glow-filled areas.
"""

import json
import sys
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from theme import W, defs, canvas, close_svg, legend, FONT, MONO

CHART_JSON = Path(__file__).parent.parent / "gh-activity-chart.json"


def load_json():
    if not CHART_JSON.exists():
        return None
    return json.loads(CHART_JSON.read_text())


def series_points(data):
    """Return five parallel arrays of cumulative values."""
    repos = [d["repos_total"] for d in data]
    opened = [d["prs_opened_total"] for d in data]
    merged = [d["prs_merged_total"] for d in data]
    closed = [d["prs_closed_total"] for d in data]
    open_ = [d["prs_open_total"] for d in data]
    return repos, opened, merged, closed, open_


def render(data):
    Wv, Hv = W, 400
    margin = {"top": 64, "right": 26, "bottom": 62, "left": 56}
    plotW = Wv - margin["left"] - margin["right"]
    plotH = Hv - margin["top"] - margin["bottom"]

    repos, opened, merged, closed, open_ = series_points(data)
    all_vals = repos + opened + open_ + merged + closed
    max_y = max(all_vals) + 8 if all_vals else 10

    def sx(i):
        return margin["left"] + (i / max(len(data) - 1, 1)) * plotW

    def sy(v):
        return margin["top"] + plotH - (v / max_y) * plotH

    def path(vals):
        pts = " ".join(f"{sx(i):.1f},{sy(v):.1f}" for i, v in enumerate(vals))
        return "M " + " L ".join(pts)

    def area(vals, base=0):
        pts = " ".join(f"{sx(i):.1f},{sy(v):.1f}" for i, v in enumerate(vals))
        last = len(vals) - 1
        pts += f" {sx(last):.1f},{sy(base):.1f}"
        pts += f" {sx(0):.1f},{sy(base):.1f}"
        return "M " + " L ".join(pts)

    parts = []
    parts.append(canvas(Wv, Hv, "a", "GitHub Activity — jlaportebot",
                        "Cumulative lifetime activity (PRs opened · repos created · merges)",
                        f"Updated {datetime.now().strftime('%b %d, %Y')}"))
    parts.append(defs("a"))

    areas = [(opened, "#58a6ff", "gO"), (repos, "#f78166", "gR")]
    for vals, color, gid in areas:
        parts.append(
            f'  <path d="{area(vals)}" fill="url(#{gid})" fill-opacity="0.14"/>'
        )

    order = [
        (opened, "#58a6ff", "PRs Opened", opened[-1]),
        (repos, "#f78166", "Repos", repos[-1]),
        (open_, "#3fb950", "Open PRs", open_[-1]),
        (merged, "#d2a8ff", "Merged", merged[-1]),
        (closed, "#f85149", "Closed", closed[-1]),
    ]
    for vals, color, label, final in order:
        parts.append(
            f'  <path d="{path(vals)}" fill="none" stroke="{color}" '
            f'stroke-width="2.6" stroke-linecap="round" stroke-linejoin="round"/>'
        )
        x, y = sx(len(vals) - 1), sy(final)
        parts.append(f'  <circle cx="{x:.1f}" cy="{y:.1f}" r="3.6" fill="{color}"/>')
        parts.append(
            f'  <text x="{x + 10:.1f}" y="{y + 4:.1f}" fill="{color}" '
            f'font-size="11" font-weight="700" font-family="{FONT}">{final}</text>'
        )

    # Y grid
    y_step = 10 if max_y > 30 else 5
    for t in range(0, max_y + 1, y_step):
        y = sy(t)
        parts.append(
            f'  <line x1="{margin["left"]:.1f}" y1="{y:.1f}" '
            f'x2="{Wv - margin["right"]:.1f}" y2="{y:.1f}" stroke="#223154" stroke-width="1"/>'
        )
        parts.append(
            f'  <text x="{margin["left"] - 9:.1f}" y="{y + 4:.1f}" fill="#5b6a90" '
            f'font-size="10" text-anchor="end" font-family="{MONO}">{t}</text>'
        )

    # X labels
    step = max(1, len(data) // 8)
    for i in range(0, len(data), step):
        x = sx(i)
        dt = datetime.strptime(data[i]["date"], "%Y-%m-%d")
        label = dt.strftime("%b %d")
        parts.append(
            f'  <line x1="{x:.1f}" y1="{margin["top"]:.1f}" x2="{x:.1f}" y2="{margin["top"] + plotH:.1f}" '
            f'stroke="#223154" stroke-width="1" stroke-dasharray="3,3"/>'
        )
        parts.append(
            f'  <text x="{x:.1f}" y="{Hv - margin["bottom"] + 20}" fill="#5b6a90" font-size="10" '
            f'text-anchor="middle" font-family="{MONO}">{label}</text>'
        )

    # Legend row under chart
    ly = Hv - 30
    items = [("Repos", "#f78166"), ("Opened", "#58a6ff"), ("Open", "#3fb950"),
             ("Merged", "#d2a8ff"), ("Closed", "#f85149")]
    parts.append(legend(margin["left"], ly + 14, items))

    parts.append(close_svg([]))
    return "\n".join(parts)


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(".")
    out.mkdir(parents=True, exist_ok=True)
    data_raw = load_json()
    if not data_raw:
        print("ERROR: gh-activity-chart.json not found — run gh_activity_chart.py first", file=sys.stderr)
        return 1
    data = data_raw.get("daily", [])
    if not data:
        print("ERROR: no daily data in gh-activity-chart.json", file=sys.stderr)
        return 1
    svg = render(data)
    svg_path = out / "gh-activity-chart.svg"
    svg_path.write_text(svg)
    print(f"Activity chart → {svg_path} ({len(svg)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
